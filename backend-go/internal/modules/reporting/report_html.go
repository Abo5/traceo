// Rendering primitives (ports of html.escape / json.dumps / str())
// ---------------------------------------------------------------------------

var escaper = strings.NewReplacer(
	"&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;", "'", "&#x27;")

// pyStr mirrors Python's str() for the values that reach the template: JSON
// numbers arrive as float64 but were written as ints, so render them as ints.
func pyStr(v any) string {
	switch t := v.(type) {
	case nil:
		return ""
	case string:
		return t
	case bool:
		if t {
			return "True"
		}
		return "False"
	case float64:
		if t == math.Trunc(t) && math.Abs(t) < 1e15 {
			return strconv.FormatInt(int64(t), 10)
		}
		return strconv.FormatFloat(t, 'g', -1, 64)
	case float32:
		return pyStr(float64(t))
	case int:
		return strconv.Itoa(t)
	case int64:
		return strconv.FormatInt(t, 10)
	case json.Number:
		return t.String()
	}
	return fmt.Sprint(v)
}

// esc — html.escape(str(v), quote=True).
func esc(v any) string { return escaper.Replace(pyStr(v)) }

// jsonIndentBytes — json.dumps(v, ensure_ascii=False, indent=2, default=str).
func jsonIndentBytes(v any) string {
	var b strings.Builder
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return pyStr(v)
	}
	return strings.TrimSuffix(b.String(), "\n")
}

func jsonish(v any) string {
	if v == nil {
		return ""
	}
	if s, ok := v.(string); ok {
		return s
	}
	return jsonIndentBytes(v)
}

// orderedJSON renders an object with the keys in the given order (Python dicts
// preserve insertion order; Go maps marshal alphabetically).
func orderedJSON(keys []string, vals []any) string {
	parts := make([]string, 0, len(keys))
	for i, k := range keys {
		kb, _ := json.Marshal(k)
		body := strings.ReplaceAll(jsonIndentBytes(vals[i]), "\n", "\n  ")
		parts = append(parts, "  "+string(kb)+": "+body)
	}
	return "{\n" + strings.Join(parts, ",\n") + "\n}"
}

// clip — display cap counted in characters, as Python's len() on a str.
func clip(text string) string {
	r := []rune(text)
	if len(r) > evidenceHTMLMax {
		return string(r[:evidenceHTMLMax]) + "…[truncated]"
	}
	return text
}

func label(l map[string]string, key string) string {
	if v, ok := l[key]; ok {
		return v
	}
	return key
}

