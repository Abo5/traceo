func runReportHTML(c *gin.Context) {
	run, ok := getRunByID(c, c.Param("id"))
	if !ok {
		return
	}
	var project models.Project
	hasProject := db.DB.First(&project, "id = ?", run.ProjectID).Error == nil
	var env models.Environment
	hasEnv := db.DB.First(&env, "id = ?", run.EnvironmentID).Error == nil

	entries := reportEntries(run)
	counts := countsOf(run, entries)
	displayID := runDisplayID(run)

	l := labels

	total := numInt(counts["total"])
	passed := numInt(counts["passed"])
	rate := "—"
	if total != 0 {
		rate = strconv.FormatFloat(float64(passed)/float64(total)*100, 'f', 1, 64) + "%"
	}

	var defects strings.Builder
	for _, e := range entries {
		if e.Outcome == "failed" || e.Outcome == "errored" {
			defects.WriteString(defectCard(e, l))
		}
	}
	defectsHTML := defects.String()
	if defectsHTML == "" {
		defectsHTML = `<div class="card">` + l["no_failures"] + `</div>`
	}

	var rows strings.Builder
	for _, e := range entries {
		var reqCells strings.Builder
		for _, r := range e.Requirements {
			reqCells.WriteString(`<div class=mono>` + esc(r.label()) + `</div>`)
		}
		reqCell := reqCells.String()
		if reqCell == "" {
			reqCell = "—"
		}
		rows.WriteString(`<tr><td>` + esc(e.TC.Title) +
			`<div class="mono" style="color:var(--muted)">` + esc(e.TC.ID) + `</div></td>` +
			`<td>` + esc(e.TC.Type) + `</td>` +
			`<td>` + esc(e.TC.Priority) + `</td>` +
			`<td><span class="badge ` + e.Outcome + `">` + esc(label(l, e.Outcome)) + `</span></td>` +
			`<td class="mono">` + strconv.Itoa(e.DurationMs) + `</td>` +
			`<td>` + reqCell + `</td>` +
			`</tr>`)
	}
	resultRows := rows.String()
	if resultRows == "" {
		resultRows = `<tr><td colspan="6">—</td></tr>`
	}

	abortHTML := ""
	if run.State == "aborted" {
		abortHTML = `<div class="card"><h3>` + l["aborted"] + `</h3>` +
			`<pre>` + esc(run.AbortReason) + `</pre></div>`
	}

	titleName := run.ProjectID
	metaName := "?"
	if hasProject {
		titleName = project.Name
		metaName = project.Name
	}
	envName := "?"
	if hasEnv {
		envName = env.Name
	}
	started := isoPtrStr(run.StartedAt)
	if started == "" {
		started = "—"
	}
	finished := isoPtrStr(run.FinishedAt)
	if finished == "" {
		finished = "—"
	}

	page := fmt.Sprintf(pageTemplate,
		l["title"], esc(titleName),
		reportCSS,
		l["title"],
		l["project"], esc(metaName),
		l["environment"], esc(envName),
		l["run"], displayID,
		esc(run.ID),
		l["state"], esc(run.State),
		l["started"], esc(started),
		l["finished"], esc(finished),
		abortHTML,
		total, l["total"],
		passed, l["passed"],
		numInt(counts["failed"]), l["failed"],
		numInt(counts["errored"]), l["errored"],
		rate, l["pass_rate"],
		l["defects"], defectsHTML,
		l["results"],
		l["case"], l["type"], l["priority"],
		l["outcome"], l["duration"], l["requirement"],
		resultRows,
		l["generated_by"], esc(iso(run.CreatedAt)),
	)
	c.Data(200, "text/html; charset=utf-8", []byte(page))
}
