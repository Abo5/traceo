func defectCard(e *reportEntry, l map[string]string) string {
	fr := e.FailureReason
	if fr == nil {
		fr = models.JSONMap{}
	}
	var reqs strings.Builder
	for _, r := range e.Requirements {
		reqs.WriteString(`<div><span class="rid mono">` + esc(r.label()) + `</span> ` +
			esc(r.Description) + `</div>`)
	}
	outcomeLbl := label(l, e.Outcome)

	diag := ""
	if fr["assertion"] != nil {
		diag = `<div class="kv">` +
			`<div class="k">` + l["assertion"] + `</div>` +
			`<div class="mono">` + esc(jsonish(fr["assertion"])) + `</div>` +
			`<div class="k">` + l["expected"] + `</div>` +
			`<div class="mono">` + esc(jsonish(fr["expected"])) + `</div>` +
			`<div class="k">` + l["actual"] + `</div>` +
			`<div class="mono">` + esc(jsonish(fr["actual"])) + `</div>` +
			`</div>`
	} else if truthy(fr["error"]) {
		diag = `<div class="kv"><div class="k">` + l["error"] + `</div>` +
			`<div class="mono">` + esc(fr["error"]) + `</div></div>`
	}

	var steps strings.Builder
	for i, raw := range e.Evidence {
		ev := asMap(raw)
		if ev == nil {
			ev = map[string]any{}
		}
		reqEv := asMap(ev["request"])
		if reqEv == nil {
			reqEv = map[string]any{}
		}
		elapsed := any(0)
		if v, ok := ev["elapsed_ms"]; ok {
			elapsed = v
		}
		steps.WriteString(`<div class="step"><div class="line mono">` +
			fmt.Sprintf("%d. ", i+1) + esc(reqEv["method"]) + " " + esc(reqEv["url"]) +
			" — " + pyStr(elapsed) + "ms</div>")

		// {k: request[k] for k in ("headers", "body") if request[k]} — insertion order.
		var keys []string
		var vals []any
		for _, k := range []string{"headers", "body"} {
			if truthy(reqEv[k]) {
				keys = append(keys, k)
				vals = append(vals, reqEv[k])
			}
		}
		if len(keys) > 0 {
			steps.WriteString(`<div class="k">` + l["request"] + `</div>` +
				`<pre>` + esc(clip(orderedJSON(keys, vals))) + `</pre>`)
		}
		if respEv, present := ev["response"]; present && respEv != nil {
			rm := asMap(respEv)
			if rm == nil {
				rm = map[string]any{}
			}
			steps.WriteString(`<div class="k">` + l["response"] + ` — HTTP ` +
				esc(rm["status"]) + `</div>` +
				`<pre>` + esc(clip(jsonish(rm["body"]))) + `</pre>`)
		} else if truthy(ev["error"]) {
			steps.WriteString(`<div class="k">` + l["error"] + `</div>` +
				`<pre>` + esc(clip(pyStr(ev["error"]))) + `</pre>`)
		}
		steps.WriteString(`</div>`)
	}
	stepsHTML := steps.String()
	if stepsHTML == "" {
		stepsHTML = "<div class=step>—</div>"
	}
	reqsHTML := reqs.String()
	if reqsHTML == "" {
		reqsHTML = " —"
	}

	return `<div class="card">` +
		`<h3>` + esc(e.TC.Title) + ` ` +
		`<span class="badge ` + e.Outcome + `">` + esc(outcomeLbl) + `</span></h3>` +
		`<div class="reqs"><strong>` + l["requirement"] + `:</strong>` + reqsHTML + `</div>` +
		diag +
		`<div class="k" style="color:var(--muted)">` +
		l["steps"] + ` / ` + l["evidence"] + `</div>` +
		stepsHTML +
		`</div>`
}

